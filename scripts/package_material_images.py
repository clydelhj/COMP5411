"""Embed runtime images in ordinary scripts so file pages need not read cross-origin image pixels."""

from pathlib import Path
import base64
import json


def package_images(root, config):
    """Package existing images without regenerating them. Encode each layer's original bytes as data URLs, write on-demand scripts and embedded paths, then synchronize browser configuration and runtime manifest. Updates config in place."""
    for layer in config["layers"]:
        images = {}
        for kind, mime in [("color", "image/jpeg"), ("detail", "image/png")]:
            data = (root / layer[kind].removeprefix("./")).read_bytes()
            images[kind] = (
                f"data:{mime};base64," + base64.b64encode(data).decode("ascii")
            )

        relative = (
            f"./assets/material-library/runtime/class-{layer['id']:02d}-embedded.js"
        )
        source = "// Local image data generated by scripts/package_material_images.py; released after each class loads.\n"
        source += (
            f"window.NOTO_MATERIAL_IMAGES[{layer['id']}] = "
            + json.dumps(images, separators=(",", ":"))
            + ";\n"
        )
        (root / relative.removeprefix("./")).write_text(source, encoding="utf-8")
        layer["embedded"] = relative

    serialized = json.dumps(config, ensure_ascii=False, indent=2)
    (root / "data/material-texture-config.js").write_text(
        "// Rock/soil classes and runtime images; maintained by the material build scripts.\nwindow.NOTO_MATERIAL_CONFIG = "
        + serialized
        + ";\n",
        encoding="utf-8",
    )
    (root / "assets/material-library/runtime/manifest.json").write_text(
        serialized,
        encoding="utf-8",
    )


if __name__ == "__main__":
    # Read the runtime manifest, package images and synchronize configuration.
    project = Path(__file__).resolve().parents[1]
    manifest = project / "assets/material-library/runtime/manifest.json"
    package_images(project, json.loads(manifest.read_text(encoding="utf-8")))
    print("Packaged 29 material layers for local HTML loading")
